//! The guest's configuration, `placeholder_map` at a log size of the bytecode, as the Lean data
//! `LeanVM/Guest/Data/Placeholders.lean`, which the Lean guest's constants read.

use super::*;
use std::fmt::Write as _;

/// A placeholder's value as a Lean term and its type: an integer, or a list of words as their limbs.
fn value(name: &str, literal: &str) -> (&'static str, String) {
    let int = |s: &str| -> u128 {
        s.trim()
            .parse()
            .unwrap_or_else(|e| panic!("placeholder {name}: `{s}` is no integer ({e})"))
    };
    match literal.strip_prefix('[').and_then(|l| l.strip_suffix(']')) {
        Some(items) => {
            let words: Vec<String> = items
                .split(',')
                .filter(|s| !s.trim().is_empty())
                .map(|s| {
                    let w = int(s);
                    format!("({}, {})", w as u64, (w >> 64) as u64)
                })
                .collect();
            ("List (Nat × Nat)", format!("[{}]", words.join(", ")))
        }
        None => ("Nat", int(literal).to_string()),
    }
}

/// `Placeholders.lean` at the log size `kbc`.
fn render(kbc: usize) -> String {
    let replacements = placeholder_map(kbc);
    let digest = hex(&keccak256::hash(placeholder_lines(&replacements).as_bytes()));
    let mut out = String::new();
    writeln!(
        out,
        "/-\n  LeanVM.Guest.Data.Placeholders\n\n  Generated by `guest-export` (lean_vm/scripts/guest-export); do not\n  \
         edit. The guest's configuration: `placeholder_map` at the bytecode's log size.\n-/\n\nmodule\n\n\
         /-!\n# The guest's placeholders\n\n`placeholder_map` (`crates/aggregation/src/placeholders.rs`) at the log size \
         `bytecodeLog`: one\ndefinition per placeholder `NAME_PLACEHOLDER`, named `NAME`, an integer or a list of words \
         as their\nlimbs. The prover computes the same map, so the guest and the prover agree on it by construction.\n\
         -/\n\nnamespace LeanVM.Guest.Placeholders\n\n@[expose] public section\n\n\
         /-- The log size of the bytecode the placeholders are computed for. -/\ndef bytecodeLog : Nat := {kbc}\n\n\
         /-- Keccak-256 of the placeholders, a line `NAME_PLACEHOLDER = value` each (`aggregation`'s \
         `placeholder_lines`):\nwith the guest's core digest, the input digest the compiled guest carries. -/\n\
         def digest : String := \"{digest}\"\n"
    )
    .unwrap();
    for (key, literal) in &replacements {
        let name = key
            .strip_suffix("_PLACEHOLDER")
            .unwrap_or_else(|| panic!("placeholder {key}: no `_PLACEHOLDER` suffix"));
        let (ty, term) = value(name, literal);
        writeln!(out, "/-- `{key}`. -/\ndef {name} : {ty} := {term}\n").unwrap();
    }
    out.push_str("end\nend LeanVM.Guest.Placeholders\n");
    out
}

/// `Placeholders.lean`, with the placeholders at the log size `kbc`.
pub fn files(kbc: usize) -> Vec<File> {
    vec![File {
        path: "LeanVM/Guest/Data/Placeholders.lean".into(),
        text: render(kbc),
    }]
}
